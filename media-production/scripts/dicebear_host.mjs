#!/usr/bin/env node
/**
 * Bakes the DiceBear "Notionists" parts chosen for the host into src/host/parts.ts.
 *
 *   node scripts/dicebear_host.mjs
 *
 * Artwork: Notionists by Zoish — CC0 1.0 (public domain), remixed here by
 * recolouring each part. Library: @dicebear/core, MIT. Both are safe for
 * commercial use; the credit lives in src/host/parts.ts and in the QC report.
 *
 * The parts stay separate (head / hair / face / clothes / gesture) so the
 * composition can move them independently — that is the whole reason for using
 * a mix-and-match system instead of one flat drawing.
 */
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';

const require = createRequire(import.meta.url);
const {Avatar, Style} = require('@dicebear/core');

const HERE = path.dirname(new URL(import.meta.url).pathname);
const STUDIO = path.dirname(HERE);
const def = JSON.parse(fs.readFileSync(path.join(
  STUDIO, 'node_modules', '@dicebear', 'styles', 'dist', 'notionists.min.json'), 'utf8'));
const style = new Style(def);

/* ---- palette -------------------------------------------------------------
   The style ships as ink (#000000) on paper (#ffffff). Each part gets its own
   paper so the character reads on the film's deep-navy backdrop, and the parts
   drawn as solid ink silhouettes (hair) get their ink tinted too.            */
const PAPER = {
  head: '#E8B58A',     // skin
  hair: '#6B4A30',     // hair highlights
  clothes: '#4A6A9C',  // blazer
  mouth: '#F6EDE2',    // teeth
  nose: '#E8B58A',
  eyes: '#FDF7F0',
  glasses: '#FDF7F0',
  eyebrows: '#6B4A30',
  gesture: '#E8B58A',
};
const INK = '#140F0B';
const INK_TINT = {hair: '#6B4A30'};

/* ---- the chosen parts ----------------------------------------------------
   Picked from the rendered lab sheets (scripts/dicebear_lab.mjs) by measuring
   ink coverage, symmetry and bbox — see REVISION-3.md.                       */
const PICKS = {
  head: 'variant01',
  clothes: 'variant14',   // flat navy front, few fold lines, symmetric
  hair: 'variant12',      // even, symmetric, medium weight
  mouth: 'variant11',     // widest, most symmetric open mouth with teeth
  nose: 'variant03',
  eyes: 'variant01',
  glasses: 'variant03',   // thin frame, no lens fill (keeps the eyes visible)
  eyebrows: 'variant02',
};
const GESTURES = ['hand', 'point', 'pointLongArm', 'okLongArm'];

const colourOf = (f) => (f && typeof f === 'object' && f.type === 'color')
  ? (f.name === 'ink' ? '#000000' : '#ffffff')
  : (typeof f === 'string' ? f : '#000000');

function bodyOf(comp, variant) {
  const v = def.components[comp].variants[variant];
  return (v.elements ?? []).map((el) => {
    const a = el.attributes ?? {};
    const attrs = Object.entries(a)
      .filter(([k]) => k !== 'fill')
      .map(([k, val]) => `${k}="${val}"`)
      .join(' ');
    const c = colourOf(a.fill);
    const fill = c === '#ffffff' ? (PAPER[comp] ?? '#ffffff') : (INK_TINT[comp] ?? INK);
    return `<${el.name} ${attrs} fill="${fill}"/>`;
  }).join('');
}

/** Pull one component's group (defs body + <use> placement) out of an avatar. */
function extract(svg, comp) {
  const gid = new RegExp(`<g id="${comp}-[a-zA-Z0-9]+-[0-9a-f]+">([\\s\\S]*?)</g>`);
  const g = svg.match(gid);
  if (!g) throw new Error(`no group for ${comp}`);
  const use = svg.match(new RegExp(`<use transform="translate\\(([-\\d.]+) ([-\\d.]+)\\)" href="#${comp}-`));
  if (!use) throw new Error(`no <use> for ${comp}`);
  return {
    x: Number(use[1]),
    y: Number(use[2]),
    body: g[1].replace(/#ffffff/g, PAPER[comp] ?? '#ffffff')
      .replace(/#000000/g, INK_TINT[comp] ?? INK),
  };
}

function render(opts) {
  return new Avatar(style, {seed: 'teacher', ...opts}).toString();
}

const out = {};
{
  const svg = render({
    hairVariant: [PICKS.hair], clothesVariant: [PICKS.clothes],
    mouthVariant: [PICKS.mouth], noseVariant: [PICKS.nose],
    eyesVariant: [PICKS.eyes], eyebrowsVariant: [PICKS.eyebrows],
    glassesProbability: 100, glassesVariant: [PICKS.glasses],
    gestureProbability: 100, gestureVariant: ['hand'],
  });
  for (const c of Object.keys(PICKS)) out[c] = extract(svg, c);
}
const gestures = {};
for (const g of GESTURES) {
  const svg = render({
    hairVariant: [PICKS.hair], clothesVariant: [PICKS.clothes],
    mouthVariant: [PICKS.mouth], noseVariant: [PICKS.nose],
    eyesVariant: [PICKS.eyes], eyebrowsVariant: [PICKS.eyebrows],
    glassesProbability: 100, glassesVariant: [PICKS.glasses],
    gestureProbability: 100, gestureVariant: [g],
  });
  gestures[g] = extract(svg, 'gesture');
}

const part = (p) => `{id: '${p.id}', x: ${p.x}, y: ${p.y}, body: \`${p.body}\`}`;
const ids = Object.fromEntries(Object.entries(out).map(([k, v]) => [k, {...v, id: k}]));

const ts = `// AUTO-GENERATED by scripts/dicebear_host.mjs — do not edit.
//
// Host artwork: "Notionists" by Zoish, licensed CC0 1.0 (public domain),
// obtained through DiceBear (@dicebear/core, MIT) and remixed here — every part
// is recoloured and the parts are animated separately. Safe for commercial use.
// Lab sheets for choosing parts: scripts/dicebear_lab.mjs.
//
// Canvas is the DiceBear 1744 x 1744 bust canvas; each part carries the
// translate() the style applies to it.

export type HostPart = {id: string; x: number; y: number; body: string};

export const HOST_CANVAS = {w: ${def.canvas.width}, h: ${def.canvas.height}};

export const HOST_HEAD: HostPart = ${part(ids.head)};
export const HOST_CLOTHES: HostPart = ${part(ids.clothes)};
export const HOST_HAIR: HostPart = ${part(ids.hair)};
export const HOST_MOUTH: HostPart = ${part(ids.mouth)};
export const HOST_NOSE: HostPart = ${part(ids.nose)};
export const HOST_EYES: HostPart = ${part(ids.eyes)};
export const HOST_GLASSES: HostPart = ${part(ids.glasses)};
export const HOST_BROWS: HostPart = ${part(ids.eyebrows)};

export const HOST_GESTURES: Record<string, HostPart> = {
${GESTURES.map((g) => `  ${g}: ${part({...gestures[g], id: g})},`).join('\n')}
};

/** Draw order the style uses: head, clothes, hair, face, gesture. */
export const HOST_PICKS = ${JSON.stringify(PICKS, null, 2)};
`;

fs.mkdirSync(path.join(STUDIO, 'src', 'host'), {recursive: true});
fs.writeFileSync(path.join(STUDIO, 'src', 'host', 'parts.ts'), ts);
console.log('wrote src/host/parts.ts');
for (const [k, v] of Object.entries(ids)) {
  console.log('  %-9s at (%d, %d)  %d chars', k, v.x, v.y, v.body.length);
}
for (const g of GESTURES) {
  console.log('  gesture %-14s at (%d, %d)  %d chars', g, gestures[g].x, gestures[g].y, gestures[g].body.length);
}
