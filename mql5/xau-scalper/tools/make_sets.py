#!/usr/bin/env python3
"""
Generate MetaTrader 5 .set preset files straight from the EA source.

Parsing the source (instead of hand-typing names) guarantees the preset keys
always match the compiled inputs -- a typo'd key in a .set file is silently
ignored by the terminal, which is the single most common "my preset did
nothing" bug.

Usage:  python3 make_sets.py <EA.mq5> <output_dir>
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

INPUT_RE = re.compile(
    r"^\s*input\s+(?P<type>[A-Za-z_]\w*)\s+(?P<name>[A-Za-z_]\w*)\s*=\s*(?P<val>[^;]+?)\s*;",
    re.M,
)

# value -> (start, step, stop) used for optimization columns
RANGES = {
    "double": ("0", "0.05", "0"),
    "int": ("0", "1", "0"),
    "long": ("0", "1", "0"),
}


def parse_inputs(src: str) -> list[tuple[str, str, str]]:
    out = []
    for m in INPUT_RE.finditer(src):
        out.append((m.group("type"), m.group("name"), m.group("val")))
    return out


def emit(inputs, overrides: dict[str, str]) -> str:
    lines = ["; XAUScalperEA preset generated by tools/make_sets.py",
             "; name=value||default||start||step||stop||N", ""]
    for typ, name, default in inputs:
        value = overrides.get(name, default)
        if typ in ("string", "bool") or typ.startswith("ENUM"):
            cols = ("0", "0", "0")
        else:
            cols = RANGES.get(typ, ("0", "1", "0"))
        lines.append(f"{name}={value}||{default}||{cols[0]}||{cols[1]}||{cols[2]}||N")
    return "\n".join(lines) + "\n"


PRESETS: dict[str, dict[str, str]] = {
    # 1) defaults straight from the source: balanced starting point
    "Balanced": {},
    # 2) capital preservation first (prop-firm / small account)
    "Conservative": {
        "InpRiskPerTradePct": "0.25",
        "InpMaxDailyLossPct": "1.5",
        "InpMaxDrawdownPct": "4.0",
        "InpMaxSpreadUSD": "0.35",
        "InpMaxTradesPerDay": "5",
        "InpConfluenceMin": "5",
        "InpSessionStartGMT": '"12:00"',
        "InpSessionEndGMT": '"18:00"',
        "InpTP1_R": "1.0",
        "InpTP1Pct": "60.0",
        "InpTP2_R": "2.0",
        "InpBEOffsetR": "0.05",
        "InpTrailStartR": "0.8",
        "InpTrailATRMult": "1.0",
        "InpMaxBarsInTrade": "60",
        "InpMaxPositions": "1",
    },
    # 3) more trades / more runners: higher variance, needs validation
    "Aggressive": {
        "InpRiskPerTradePct": "0.5",
        "InpMaxDailyLossPct": "2.0",
        "InpMaxDrawdownPct": "6.0",
        "InpMaxSpreadUSD": "0.55",
        "InpMaxTradesPerDay": "12",
        "InpConfluenceMin": "3",
        "InpSessionStartGMT": '"07:00"',
        "InpSessionEndGMT": '"20:00"',
        "InpTP1_R": "1.0",
        "InpTP1Pct": "40.0",
        "InpTP2_R": "3.0",
        "InpTrailStartR": "1.2",
        "InpTrailATRMult": "1.5",
        "InpMaxBarsInTrade": "120",
        "InpCooldownBars": "1",
    },
}


def main() -> int:
    if len(sys.argv) < 3:
        print("usage: make_sets.py <EA.mq5> <output_dir>")
        return 2
    src = Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace")
    outdir = Path(sys.argv[2])
    outdir.mkdir(parents=True, exist_ok=True)

    inputs = parse_inputs(src)
    if not inputs:
        print("ERROR: no inputs parsed - check INPUT_RE")
        return 1
    print(f"parsed {len(inputs)} inputs from {Path(sys.argv[1]).name}")

    for name, overrides in PRESETS.items():
        unknown = set(overrides) - {i[1] for i in inputs}
        if unknown:
            print(f"ERROR: preset '{name}' overrides unknown inputs: {sorted(unknown)}")
            return 1
        path = outdir / f"XAUScalper-{name}.set"
        path.write_text(emit(inputs, overrides), encoding="utf-8")
        print(f"  wrote {path} ({len(overrides)} overrides)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
