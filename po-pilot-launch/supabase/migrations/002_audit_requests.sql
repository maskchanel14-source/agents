-- PO Pilot: paid audit service requests
-- Project: po-pilot-leads (tkoerwqgpzwxcbbqzbwg)
-- The anon key used by /audit/ can INSERT only (verified: direct select as anon returns
-- "permission denied for table audit_requests").

create table if not exists public.audit_requests (
  id bigint generated by default as identity primary key,
  email text not null,
  name text,
  store_url text,
  sku_count text,
  vendor_count text,
  tier text,
  pain text,
  timeline text,
  source text default 'audit-page',
  page_url text,
  referrer text,
  user_agent text,
  status text not null default 'new',
  created_at timestamptz not null default now()
);

create index if not exists audit_requests_created_idx
  on public.audit_requests (created_at desc);

alter table public.audit_requests enable row level security;

drop policy if exists "anon_can_insert_audit" on public.audit_requests;
create policy "anon_can_insert_audit"
  on public.audit_requests
  for insert
  to anon, authenticated
  with check (true);

grant insert on public.audit_requests to anon, authenticated;
grant usage, select on sequence public.audit_requests_id_seq to anon, authenticated;

revoke all on public.audit_requests from anon;
grant insert on public.audit_requests to anon;

comment on table public.audit_requests is
  'Paid PO audit service ($250/$450/$750) inbound requests. Insert-only for anon. status: new/quoted/won/lost.';
