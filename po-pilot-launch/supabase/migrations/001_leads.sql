-- PO Pilot launch: lead capture
-- Project: po-pilot-leads (tkoerwqgpzwxcbbqzbwg)
-- The anon key used by the landing page can INSERT only. It cannot read, update or delete.

create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  email text not null,
  first_name text,
  store_url text,
  sku_range text,
  source text default 'landing',
  page_url text,
  referrer text,
  user_agent text,
  created_at timestamptz not null default now()
);

create unique index if not exists leads_email_key on public.leads (lower(email));

alter table public.leads enable row level security;

drop policy if exists "anon_can_insert_leads" on public.leads;
create policy "anon_can_insert_leads"
  on public.leads
  for insert
  to anon, authenticated
  with check (true);

grant insert on public.leads to anon, authenticated;
grant usage, select on sequence public.leads_id_seq to anon, authenticated;

-- anon must not be able to read the list back out
revoke all on public.leads from anon;
grant insert on public.leads to anon;

comment on table public.leads is
  'PO Pilot launch: free checklist + kit lead capture. Insert-only for anon; read via dashboard/service role.';
